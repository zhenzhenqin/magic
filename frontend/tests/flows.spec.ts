test('九项权限独立、单向授权、用对方视角验证并撤销', async ({ page }) => {
  await page.goto('/friends/man/permissions')
  await expect(page.getByText('对方暂未共享。')).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(9)
  await expect(page.getByRole('checkbox', { name: '饮食记录', exact: true })).toBeChecked()
  await page.getByRole('checkbox', { name: '食物名称', exact: true }).uncheck()
  await page.getByRole('checkbox', { name: '文字备注', exact: true }).check()
  await page.getByRole('button', { name: '用对方视角查看' }).click()
  await expect(page.getByRole('heading', { name: '小林的手账' })).toBeVisible()
  await expect(page.getByRole('button', { name: '共享食物' }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: '黄油可颂' })).toHaveCount(0)
  await expect(page.getByText('楼下烘焙店的可颂，今天也刚好出炉。')).toBeVisible()
  await page.getByRole('button', { name: '2026-11-24', exact: true }).click()
  await expect(page.getByText('好友仅分享当天记录。')).toBeVisible()
  await account(page, 'lin')
  await page.goto('/friends/man/diary')
  await expect(page.getByText('好友尚未授权你查看饮食记录。')).toBeVisible()
  await page.goto('/friends/man/permissions')
  await page.getByRole('button', { name: '停止全部共享' }).click()
  await page.getByRole('button', { name: '确认停止共享' }).click()
  await expect(page.getByRole('checkbox', { name: '饮食记录', exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: '用对方视角查看' }).click()
  await expect(page).toHaveURL('/friends/lin/diary')
  await page.reload()
  await expect(page.getByText('好友尚未授权你查看饮食记录。')).toBeVisible()
})

