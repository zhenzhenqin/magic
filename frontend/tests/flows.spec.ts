  await expect(page.getByRole('dialog').getByText('热量 270 kcal')).toBeVisible()
  await page.getByRole('button', { name: '关闭弹窗' }).click()
  await page.getByRole('link', { name: '月历', exact: true }).click()
  await expect(page.getByRole('link', { name: '2026-11-27 有记录' })).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: '图鉴', exact: true }).click()
  await page.getByRole('searchbox').fill('柠檬烤鱼')
  await expect(page.locator('.catalog-entry')).toHaveCount(1)
  await page.goto('/?date=2026-11-27')
  await page.getByRole('button', { name: '柠檬烤鱼', exact: true }).click()
