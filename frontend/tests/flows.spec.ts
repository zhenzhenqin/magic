import { expect, test } from '@playwright/test'
import { account, demoClock, pickAndRecognize } from './demo-fixtures'

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(demoClock)
})

test('手账日期、月历往返与键盘关闭食物详情', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '美食手账', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '2026-11-24', exact: true }).click()
  await expect(page.getByRole('button', { name: '番茄炒蛋' })).toBeVisible()
  await page.getByRole('button', { name: '番茄炒蛋' }).press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: '番茄炒蛋' })).toBeFocused()
  await page.getByRole('link', { name: '月历', exact: true }).click()
  await expect(page.getByRole('heading', { name: '2026年11月' })).toBeVisible()
  await page.getByRole('button', { name: '上个月' }).click()
  await expect(page.getByRole('heading', { name: '2026年10月' })).toBeVisible()
  await page.getByRole('button', { name: '下个月' }).click()
  await page.getByRole('link', { name: '2026-11-25 有记录' }).click()
  await expect(page).toHaveURL('/?date=2026-11-25')
  await page.goBack()
  await expect(page.getByRole('heading', { name: '饮食月历' })).toBeVisible()
})

